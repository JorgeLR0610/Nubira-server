import os
import sqlite3
import time
from contextlib import closing, contextmanager
from datetime import datetime, timezone
from pathlib import Path

from config import database_url


class DatabaseUnavailable(RuntimeError):
    """The PostgreSQL operation could not complete."""


class Database:
    def __init__(self, connection, *, postgres: bool):
        self.connection = connection
        self.postgres = postgres

    def execute(self, statement, parameters=()):
        # The statements are static application SQL; values are always bound separately.
        if self.postgres:
            statement = statement.replace("?", "%s")
        return self.connection.execute(statement, parameters) if parameters else self.connection.execute(statement)

    def lock(self, statement, parameters=(), *, clause="FOR UPDATE"):
        if self.postgres:
            statement = f"{statement} {clause}"
        else:
            self.connection.execute("BEGIN IMMEDIATE")
        return self.execute(statement, parameters)


def database_path() -> Path:
    return Path(os.environ.get("NUBIRA_DB_PATH", Path(__file__).parent / "workspace" / "nubira.sqlite3"))


@contextmanager
def database():
    if url := database_url():
        import psycopg
        from psycopg.rows import dict_row

        # Don't reuse connections that may have been interrupted by Neon idling.
        try:
            conn = psycopg.connect(url, connect_timeout=10, row_factory=dict_row)
        except (psycopg.OperationalError, psycopg.ProgrammingError):
            raise DatabaseUnavailable("No se pudo conectar con PostgreSQL.") from None
        try:
            # Commit/rollback and close per operation; never replay a potentially committed write.
            with conn:
                yield Database(conn, postgres=True)
        except psycopg.OperationalError:
            raise DatabaseUnavailable("No se pudo completar la operación con PostgreSQL.") from None
        return
    with closing(sqlite3.connect(database_path(), timeout=10)) as conn, conn:
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        yield Database(conn, postgres=False)


def schema(postgres: bool) -> str:
    user_id = "BIGINT GENERATED BY DEFAULT AS IDENTITY" if postgres else "INTEGER"
    coordinates = "DOUBLE PRECISION" if postgres else "REAL"
    # Keep ISO dates and serialized JSON to preserve the API representation across both databases.
    return f"""
            CREATE TABLE IF NOT EXISTS users (
                id {user_id} PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                verified_at BIGINT
            );
            CREATE TABLE IF NOT EXISTS sessions (
                digest TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS account_tokens (
                digest TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                purpose TEXT NOT NULL,
                expires BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS rate_limits (
                key TEXT PRIMARY KEY,
                count INTEGER NOT NULL,
                expires BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS place_cache (
                key TEXT PRIMARY KEY,
                response TEXT NOT NULL,
                expires BIGINT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS events (
                id TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                name TEXT NOT NULL,
                latitude {coordinates} NOT NULL,
                longitude {coordinates} NOT NULL,
                target_date TEXT NOT NULL,
                prediction TEXT NOT NULL,
                evaluated_at TEXT NOT NULL,
                created_at TEXT NOT NULL,
                alerts INTEGER NOT NULL DEFAULT 0,
                alert_baseline TEXT
            );
            CREATE INDEX IF NOT EXISTS events_owner ON events(user_id, target_date);
            CREATE TABLE IF NOT EXISTS alert_outbox (
                id TEXT PRIMARY KEY,
                event_id TEXT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
                subject TEXT NOT NULL,
                body TEXT NOT NULL,
                due BIGINT NOT NULL,
                attempts INTEGER NOT NULL DEFAULT 0,
                lease_until BIGINT NOT NULL DEFAULT 0,
                sent_at BIGINT
            );
        """


def init_database():
    if not database_url():
        path = database_path()
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        path.touch(mode=0o600, exist_ok=True)
    with database() as conn:
        if conn.postgres:
            # Serialize schema setup if two deployments start at the same time.
            conn.execute("SELECT pg_advisory_xact_lock(684120904)")
        else:
            conn.execute("PRAGMA journal_mode = WAL")
        for statement in schema(conn.postgres).split(";"):
            if statement.strip():
                conn.execute(statement)


def prune_database():
    now = int(time.time())
    today = datetime.fromtimestamp(now, timezone.utc).date().isoformat()
    with database() as conn:
        conn.execute("DELETE FROM sessions WHERE expires <= ?", (now,))
        conn.execute("DELETE FROM account_tokens WHERE expires <= ?", (now,))
        conn.execute("DELETE FROM rate_limits WHERE expires <= ?", (now,))
        conn.execute("DELETE FROM place_cache WHERE expires <= ?", (now,))
        conn.execute("DELETE FROM alert_outbox WHERE sent_at <= ?", (now - 30 * 86400,))
        conn.execute("""
            DELETE FROM alert_outbox WHERE sent_at IS NULL AND event_id IN
            (SELECT id FROM events WHERE target_date <= ?)
        """, (today,))
